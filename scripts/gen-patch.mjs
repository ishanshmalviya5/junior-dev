// Generate cordis.patch.yml: the host row + the junior-dev preset (a copy of the installed `standard`
// preset — presets cannot extend each other — with the junior-dev persona and tools rows).
// Usage: node scripts/gen-patch.mjs [path/to/dsh]   (default: the global install)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { PROTOCOL } from '../lib/host/prompts.js';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const dsh = process.argv[2] ?? '/opt/homebrew/lib/node_modules/@deepseek-ai/dsh';
const std = fs.readFileSync(path.join(dsh, 'node_modules/@deepseek-ai/dsh-web-app/presets/standard.patch.yml'), 'utf8');
const version = JSON.parse(fs.readFileSync(path.join(dsh, 'package.json'), 'utf8')).version;

// Keep the standard plugin list verbatim from "plugins:" on.
const at = std.indexOf('        plugins:\n');
if (at < 0) throw new Error('unexpected standard.patch.yml layout');
let plugins = std.slice(at + '        plugins:\n'.length);

// Replace the persona row's config with the junior-dev protocol.
const personaRe = /( {10}- id: persona\n {12}name: '@deepseek-ai\/dsh-persona'\n {12}config:\n)( {14}.*\n)+/;
if (!personaRe.test(plugins)) throw new Error('persona row not found');
const indent = (s, n) => s.split('\n').map((l) => (l ? ' '.repeat(n) + l : l)).join('\n');
plugins = plugins.replace(personaRe, (_m, head) => `${head}              suffix: ''\n              prefix: |\n${indent(PROTOCOL, 16)}\n`);
// The skills folder is mounted so the developer can invoke the practice skills (as DSH's creator preset does).
const skillRe = /( {10}- id: skill-filesystem\n {12}name: '@deepseek-ai\/dsh-skill-filesystem'\n)/;
if (!skillRe.test(plugins)) throw new Error('skill-filesystem row not found');
const skillsDir = "!!js process.getBuiltinModule('node:path').join(process.getBuiltinModule('node:path').dirname(process.getBuiltinModule('node:module').createRequire(baseUrl).resolve('junior-dev/package.json')), 'skills')";
plugins = plugins.replace(skillRe, (m) => `${m}            config:\n              customSkillDirs:\n                - ${skillsDir}\n`);
plugins = plugins.trimEnd() + `\n          - id: junior-dev-tools\n            name: junior-dev/tools\n`;

const out = `# GENERATED by scripts/gen-patch.mjs from @deepseek-ai/dsh ${version} — do not edit by hand.
# Row 1: the junior-dev host plugin (run registry, permission gate, progress route).
# Row 2: the junior-dev agent preset: a copy of the standard preset (presets cannot extend
#        each other) with the junior-dev protocol as persona and the jd_* tools row.
- insert:
    - id: junior-dev
      name: junior-dev
    - id: preset-junior-dev
      name: '@deepseek-ai/dsh-agent-preset'
      config:
        id: junior-dev
        name: Junior Dev
        description: Paste a PRD. junior-dev interviews you to parity, then builds, verifies and delivers it unattended.
        order: 5
        plugins:
${plugins}`;
fs.writeFileSync(path.join(root, 'cordis.patch.yml'), out);
console.log(`cordis.patch.yml written from dsh ${version} (${out.split('\n').length} lines)`);
